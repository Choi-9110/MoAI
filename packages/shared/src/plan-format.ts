import type { PlanSection } from './plan-doc';

/**
 * 사업계획서 양식.
 *
 * 요약 한 장까지는 트랙이 갈려 있어도 결과물이 같다. 갈리는 건 그 다음,
 * **어떤 틀에 부어 넣느냐**다. 세 가지가 있다.
 *
 * - pssd: 모두의창업 **1인 창업**. P–S–S–**D**(향후 발전방안).
 * - psst: 모두의창업 **팀 창업**. P–S–S–**T**(팀 구성).
 * - gov:  일반 정부지원사업. 공고에 붙은 양식을 올리면 거기서 목차를 뽑고,
 *         없으면 **연구개발과제인지 판정**해 R&D 표준 8항목 또는 일반 사업화
 *         8항목으로 쓴다 (`plan-doc.ts` 의 RND_OUTLINE · GENERAL_OUTLINE).
 *         PSSD·PSST 는 모두의창업 전용이라 여기 기본값이 될 수 없다.
 *
 * **PSSD 와 PSST 는 마지막 칸만 다르다.** 혼자 하면 쓸 팀이 없으니 그 자리에
 * 멘토링 이후의 변화를 쓰고(D), 팀이 있으면 팀 구성을 쓴다(T). Q1~Q3 은 같다.
 *
 * 둘 다 목차가 정해져 있다. 그래서 모델에게 목차를 물어보지 않고 **여기 박아
 * 둔 것을 그대로 쓴다.** 양식이 뻔한데 매번 물어보면 느리기만 하고, 답이
 * 조금씩 달라져서 더 나쁘다.
 */
export const PLAN_FORMATS = ['pssd', 'psst', 'gov'] as const;
export type PlanFormat = (typeof PLAN_FORMATS)[number];

type Outline = Omit<PlanSection, 'body' | 'openQuestions'>[];

export interface PlanFormatSpec {
  label: string;
  /** 고를 때 보여줄 한 줄 */
  summary: string;
  /** 어떤 사업에 쓰는 양식인가 */
  when: string;
  /**
   * 작성 지침 파일 (`docs/references/frameworks/` 기준 상대 경로).
   *
   * 원본은 PDF·강의자료지만 매번 읽히면 느리고 비싸서, 한 번 읽어
   * 지침만 뽑아 MD 로 만들어 두었다. 실행기가 이 파일을 읽는다.
   */
  guide: string | null;
  /**
   * 주최측이 정해 둔 목차가 있는가.
   *
   * 있어도 **양식 파일을 올리면 그쪽이 이긴다.** 우리가 아는 목차는
   * 공개된 자료에서 옮긴 것이고, 사용자가 손에 든 양식이 그 해의 진짜다.
   */
  fixedOutline: boolean;
  /**
   * 이 양식에 **없는** 칸.
   *
   * 올린 양식에는 있는데 이 틀에는 대응할 칸이 없는 항목이 반드시 생긴다.
   * PSSD 에는 팀 구성 칸이 없고, PSST 에는 멘토링 후 변화 칸이 없다.
   * 그런 절에 억지로 칸을 붙이면 "팀 소개가 아니다" 같은 지침이 하필
   * 팀 소개를 쓰는 절에 걸려서, 양식과 지침이 서로를 부순다.
   */
  frameCaveat?: string;
  /**
   * 이 양식에서만 **이미 확정된 사실**. 절마다 프롬프트에 함께 넣는다.
   *
   * 지원금 액수, 라운드 구성, 평가 방식처럼 공고가 못 박아 둔 것이다.
   * 이게 없으면 모델이 자금 계획을 "○○만원 규모로 추정" 식으로 지어내는데,
   * 심사자는 자기가 주는 돈의 액수를 알고 있어서 그 한 줄에서 바로 걸린다.
   */
  context?: string;
}

