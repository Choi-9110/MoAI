/**
 * 공고 유형별 작성 가이드.
 *
 * 같은 아이템이라도 **어디에 내느냐에 따라 심사자가 보는 것이 다르다.**
 * R&D 과제는 기술 수준과 성능 지표를 보고, 창업지원은 시장과 매출을 보고,
 * 모두의창업은 라운드를 올라갈 사람인지를 본다. 그걸 모르고 쓰면 열심히
 * 쓴 것이 배점 없는 칸에 들어간다.
 *
 * 내용은 지어낸 것이 아니다. 셋으로 나뉜다.
 *
 * - 사업계획서를 쓰는 유형(모두의창업·R&D·창업지원)은 `docs/references/
 *   frameworks/` 의 작성 지침에서 뽑았다. 사업계획서를 쓸 때 실행기가 읽는
 *   것과 **같은 자료**다 — 화면에서 보는 것과 AI 가 따르는 것이 다르면 안 된다.
 * - 공모전·입주공간·해외진출·투자는 **우리가 수집한 공고 3만 건**에서
 *   실제 모집 방식과 요건을 훑어 정리했다.
 * - 바우처는 수출바우처 포털·중진공 안내에서 확인했다 (메뉴판 방식,
 *   1차 서류 → 2차 현장평가, 자부담 매칭 구조).
 */

export type GuideBlock =
  | { kind: 'text'; text: string }
  | { kind: 'list'; items: string[] }
  | { kind: 'table'; head: string[]; rows: string[][] }
  | { kind: 'compare'; rows: { bad: string; good: string }[] }
  | { kind: 'note'; text: string };

export interface GuideSection {
  title: string;
  blocks: GuideBlock[];
}

export interface GuideType {
  key: string;
  label: string;
  /** 어떤 공고가 여기 해당하는가 */
  when: string;
  sections: GuideSection[];
}

